def text_width(s):
    """글자 폭 3 + 사이 1. 끝의 사이는 뺀다."""
    return max(0, len(s) * 4 - 1)


def text_pixels(s):
    """문자열 → 칠할 (x, y) 칸들. 모르는 글자는 '?' 로."""
    for i, ch in enumerate(s.upper()):
        rows = GLYPHS.get(ch, GLYPHS["?"])
        for y, row in enumerate(rows):
            for x, c in enumerate(row):
                if c == "#":
                    yield i * 4 + x, y


